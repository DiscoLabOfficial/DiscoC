namespace {

// Direct-page scratch bytes used inside one IR instruction ($04-$1F are
// caller-saved under the SPC700 ABI, so no value survives a call here).
constexpr unsigned Pointer = 0x04; // address of an indirect access
constexpr unsigned T0 = 0x06;      // left operand / dividend / quotient
constexpr unsigned T1 = 0x08;      // right operand / divisor
constexpr unsigned T2 = 0x0A;      // result
constexpr unsigned T3 = 0x0C;      // remainder
constexpr unsigned Signs = 0x0E;   // division signs, shift and epilogue temporaries
constexpr unsigned FarFrame = 0x1C; // FP + offset for slots beyond [FP]+255

std::string stripPrivate(const std::string& name) {
    return !name.empty() && name.front() == '\x01' ? name.substr(1) : name;
}

// The assembler reads a trailing `.digits` as a bit selector, so such names
// cannot appear as plain symbol operands.
bool assemblable(const std::string& name) {
    if (name.empty()) return false;
    const auto first = static_cast<unsigned char>(name.front());
    if (!(std::isalpha(first) || name.front() == '_' || name.front() == '.')) return false;
    for (const char c : name)
        if (!(std::isalnum(static_cast<unsigned char>(c)) || c == '_' || c == '.')) return false;
    const auto dot = name.find_last_of('.');
    return dot == std::string::npos || name.find_first_not_of("0123456789", dot + 1) != std::string::npos;
}

} // namespace

SPC700CodeGenerator::SPC700CodeGenerator(
    const std::map<std::string, Analyzer::LocalSymbolTable>& local_symbols,
    const std::map<std::string, FunctionSymbol>& function_symbols,
    const DataSegmentManager& data, const CompilerConfig& config)
    : m_local_symbols(local_symbols), m_function_symbols(function_symbols), m_data(data), m_config(config) {}

// ---- Emission helpers -------------------------------------------------------

void SPC700CodeGenerator::emit(const std::string& line) { m_out << "    " << line << '\n'; }

void SPC700CodeGenerator::bind(const std::string& label) { m_out << label << ":\n"; }

std::string SPC700CodeGenerator::newLabel() {
    return "__disco_f" + std::to_string(m_function_index) + "_l" + std::to_string(m_label_serial++);
}

std::string SPC700CodeGenerator::blockLabel(IRBlockId block) const {
    return "__disco_f" + std::to_string(m_function_index) + "_b" + std::to_string(block.value);
}

std::string SPC700CodeGenerator::epilogueLabel() const {
    return "__disco_f" + std::to_string(m_function_index) + "_ret";
}

std::string SPC700CodeGenerator::hex8(unsigned value) {
    static const char* digits = "0123456789ABCDEF";
    std::string text = "$";
    text += digits[(value >> 4) & 15];
    text += digits[value & 15];
    return text;
}

std::string SPC700CodeGenerator::hex16(unsigned value) {
    return hex8((value >> 8) & 0xFF) + hex8(value & 0xFF).substr(1);
}

std::string SPC700CodeGenerator::dp(unsigned address) { return hex8(address); }

void SPC700CodeGenerator::unsupported(const std::string& what, const Token& source) const {
    throw CompilerError("SPC700 backend does not lower " + what + " yet.", source);
}

void SPC700CodeGenerator::internal(const std::string& what, const Token& source) const {
    throw CompilerError("Internal Compiler Error: SPC700 codegen: " + what, source);
}

// ---- Module -----------------------------------------------------------------

ObjectFile SPC700CodeGenerator::generate(const IRModule& module) {
    const auto text = generateAssembly(module);
    try {
        return Assembler(TargetKind::SPC700).assemble(text);
    } catch (const CompilerError& error) {
        // Generated text that does not assemble is a backend bug.
        throw CompilerError("Internal Compiler Error: SPC700 codegen produced invalid assembly: " +
                            error.getMessage() + " (line " + std::to_string(error.getLine()) + ")", 1, 1);
    }
}

std::string SPC700CodeGenerator::generateAssembly(const IRModule& module) {
    if (module.target != TargetKind::SPC700) throw std::logic_error("SPC700 codegen received a non-SPC700 module.");
    m_out.str({});
    m_out.clear();
    m_uses_unsigned_division = m_uses_signed_division = false;
    m_out << "; SPC700 code generated by discc.\n.setcpu \"SPC700\"\n"
          << ".define __DISCO_CODE_START_ADDRESS " << hex16(m_config.code_start_address & 0xFFFF) << '\n';
    // Section alignment is declared once, before any statement.
    std::uint8_t ram_alignment = 2;
    for (const auto& pair : m_data.getEntries())
        if (!pair.second.is_extern && pair.second.storage == AddressSpace::RAM)
            ram_alignment = static_cast<std::uint8_t>(std::max<int>(ram_alignment, pair.second.type.alignment));
    m_out << ".define __DISCO_DATA_ALIGNMENT 2\n.define __DISCO_RAM_ALIGNMENT "
          << static_cast<unsigned>(ram_alignment) << "\n\n.segment \"CODE\"\n";
    for (m_function_index = 0; m_function_index < module.functions.size(); ++m_function_index)
        emitFunction(module.functions[m_function_index]);
    m_function = nullptr;
    emitDivisionHelpers();
    emitData();
    return m_out.str();
}

std::string SPC700CodeGenerator::functionLabel(const std::string& name, bool& exported) const {
    const auto found = m_function_symbols.find(name);
    const auto link = found != m_function_symbols.end() && !found->second.link_name.empty() ? found->second.link_name : name;
    exported = link.empty() || link.front() != '\x01';
    const auto label = stripPrivate(link);
    if (!assemblable(label))
        throw CompilerError("SPC700 backend cannot name the symbol '" + label + "' in assembly.", 1, 1);
    return label;
}

void SPC700CodeGenerator::emitData() {
    bool any_data = false, any_ram = false;
    for (const auto& pair : m_data.getEntries()) {
        if (pair.second.is_extern) continue;
        (pair.second.storage == AddressSpace::RAM ? any_ram : any_data) = true;
    }
    const auto section = [&](bool ram) {
        m_out << "\n.segment \"" << (ram ? "RAM" : "DATA") << "\"\n";
        std::size_t size = 0;
        for (const auto& pair : m_data.getEntries()) {
            const auto& entry = pair.second;
            if (entry.is_extern || (entry.storage == AddressSpace::RAM) != ram) continue;
            // `rom` data has no separate address space on SPC700: it lives in
            // the payload's DATA, and stores to it are rejected earlier.
            const auto alignment = static_cast<std::size_t>(ram ? std::max(2, entry.type.alignment) : 2);
            while (size % alignment) { emit(".byte $00"); ++size; }
            const auto label = stripPrivate(entry.link_name);
            if (!assemblable(label))
                throw CompilerError("SPC700 backend cannot name the symbol '" + label + "' in assembly.", 1, 1);
            if (entry.link_name.empty() || entry.link_name.front() != '\x01') m_out << ".export " << label << '\n';
            bind(label);
            for (std::size_t offset = 0; offset < entry.bytes.size(); offset += 16) {
                std::string line = ".byte ";
                for (std::size_t i = offset; i < entry.bytes.size() && i < offset + 16; ++i)
                    line += (i == offset ? "" : ", ") + hex8(entry.bytes[i]);
                emit(line);
            }
            size += entry.bytes.size();
        }
    };
    if (any_data) section(false);
    if (any_ram) section(true);
}

// ---- Functions and frames ---------------------------------------------------

const Analyzer::LocalSymbolTable& SPC700CodeGenerator::locals() const {
    static const Analyzer::LocalSymbolTable empty;
    const auto found = m_local_symbols.find(m_function->name);
    return found == m_local_symbols.end() ? empty : found->second;
}

int SPC700CodeGenerator::slotBytes(const Type& type, const Token& source) const {
    if (isFarPointer(type)) unsupported("far pointers (unavailable on SPC700)", source);
    if (type.pointer_level > 0) return 2;
    if (type.base == BaseType::STRUCT) unsupported("aggregate values", source);
    if (type.base == BaseType::VOID) return 0;
    return usesByteStorage(type) ? 1 : 2;
}

void SPC700CodeGenerator::layoutFrame(const IRFunction& function) {
    m_frame = Frame{};
    // The analyzer lays out locals below FP for the GSU ABI (negative offsets,
    // total `total_local_alloc_size`). SPC700 frames grow upward from FP, so
    // that region is moved, unchanged in its internal layout, to FP+2.
    m_frame.locals = (function.total_local_alloc_size + 1) & ~1;
    m_producers.assign(function.value_count + 1, nullptr);
    int values = 0;
    for (const auto& block : function.blocks) {
        for (const auto& instruction : block.instructions) {
            if (!instruction.result.isValid()) continue;
            if (instruction.result.value >= m_producers.size()) internal("value id out of range", instruction.source);
            m_producers[instruction.result.value] = &instruction;
            const auto bytes = slotBytes(instruction.type, instruction.source);
            m_frame.value_offsets[instruction.result.value] = 2 + m_frame.locals + values;
            values += bytes;
        }
    }
    m_frame.values = (values + 1) & ~1;
    m_frame.arguments = 2 + m_frame.locals + m_frame.values;
    if (m_frame.arguments + 2 * static_cast<int>(function.parameters.size()) > 0x7FFF)
        throw CompilerError("SPC700 stack frame of '" + function.name + "' exceeds 32 KiB.", 1, 1);
}

int SPC700CodeGenerator::localOffset(int analyzer_offset) const { return 2 + m_frame.locals + analyzer_offset; }

int SPC700CodeGenerator::parameterOffset(int analyzer_offset) const {
    // Analyzer parameter offsets start at the GSU's first parameter slot and
    // advance one word per argument, which is also the SPC700 slot size.
    return m_frame.arguments + analyzer_offset - 6;
}

void SPC700CodeGenerator::emitFunction(const IRFunction& function) {
    m_function = &function;
    m_label_serial = 0;
    layoutFrame(function);
    bool exported = false;
    const auto label = functionLabel(function.name, exported);
    m_out << '\n';
    if (exported) m_out << ".export " << label << '\n';
    bind(label);
    emitPrologue();
    for (const auto& block : function.blocks) emitBlock(block);
    emitEpilogue();
}

void SPC700CodeGenerator::emitPrologue() {
    const auto bytes = m_frame.bytes();
    const auto limit = "__disco_stack_limit_" + std::to_string(bytes);
    const auto hardware_ok = newLabel(), ok = newLabel();
    // Return addresses live in the 256-byte hardware stack: refuse to go
    // deeper rather than let CALL wrap around page 1.
    emit("mov x,sp");
    emit("cmp x,#" + hex8(SPC700Target::Abi::HardwareStackReserve));
    emit("bcs " + hardware_ok);
    emitFault(SPC700Target::Fault::InvalidAddress);
    bind(hardware_ok);
    // The callee needs `bytes` more bytes: SSP must be at least the stack
    // floor plus that amount, or the frame would overwrite static storage.
    emit("mov a,#<" + limit);
    emit("mov y,#>" + limit);
    emit("movw " + dp(T0) + ",ya");
    emit("movw ya,$00");
    emit("cmpw ya," + dp(T0));
    emit("bcs " + ok);
    emitFault(SPC700Target::Fault::InvalidAddress);
    bind(ok);
    emit("mov a,$00");
    emit("setc");
    emit("sbc a,#" + hex8(bytes & 0xFF));
    emit("mov $00,a");
    emit("mov a,$01");
    emit("sbc a,#" + hex8((bytes >> 8) & 0xFF));
    emit("mov $01,a");
    emit("mov y,#$00");
    emit("mov a,$02");
    emit("mov [$00]+y,a");
    emit("inc y");
    emit("mov a,$03");
    emit("mov [$00]+y,a");
    emit("movw ya,$00");
    emit("movw $02,ya");
}

void SPC700CodeGenerator::emitEpilogue() {
    const auto bytes = m_frame.bytes();
    bind(epilogueLabel());
    emit("movw ya,$02");
    emit("movw $00,ya");
    emit("mov y,#$00");
    emit("mov a,[$00]+y");
    emit("mov " + dp(Signs) + ",a");
    emit("inc y");
    emit("mov a,[$00]+y");
    emit("mov $03,a");
    emit("mov a," + dp(Signs));
    emit("mov $02,a");
    emit("mov a,$00");
    emit("clrc");
    emit("adc a,#" + hex8(bytes & 0xFF));
    emit("mov $00,a");
    emit("mov a,$01");
    emit("adc a,#" + hex8((bytes >> 8) & 0xFF));
    emit("mov $01,a");
    emit("movw ya," + dp(T2)); // Result: YA for words, A for bytes.
    emit("ret");
}

// ---- Frame and value access -------------------------------------------------

const IRInstruction& SPC700CodeGenerator::producer(IRValueId value, const Token& source) const {
    if (!value.isValid() || value.value >= m_producers.size() || !m_producers[value.value])
        internal("operand has no producer", source);
    return *m_producers[value.value];
}

const Type& SPC700CodeGenerator::typeOf(IRValueId value, const Token& source) const {
    return producer(value, source).type;
}

void SPC700CodeGenerator::frameRead(int offset, unsigned destination, int bytes) {
    if (offset >= 0 && offset + bytes - 1 <= 255) {
        for (int i = 0; i < bytes; ++i) {
            emit("mov y,#" + hex8(static_cast<unsigned>(offset + i)));
            emit("mov a,[$02]+y");
            emit("mov " + dp(destination + static_cast<unsigned>(i)) + ",a");
        }
        return;
    }
    // Beyond [FP]+255: address the slot through FP + offset.
    emit("mov a,$02");
    emit("clrc");
    emit("adc a,#" + hex8(static_cast<unsigned>(offset) & 0xFF));
    emit("mov " + dp(FarFrame) + ",a");
    emit("mov a,$03");
    emit("adc a,#" + hex8((static_cast<unsigned>(offset) >> 8) & 0xFF));
    emit("mov " + dp(FarFrame + 1) + ",a");
    for (int i = 0; i < bytes; ++i) {
        emit("mov y,#" + hex8(static_cast<unsigned>(i)));
        emit("mov a,[" + dp(FarFrame) + "]+y");
        emit("mov " + dp(destination + static_cast<unsigned>(i)) + ",a");
    }
}

void SPC700CodeGenerator::frameWrite(int offset, unsigned source, int bytes) {
    if (offset >= 0 && offset + bytes - 1 <= 255) {
        for (int i = 0; i < bytes; ++i) {
            emit("mov y,#" + hex8(static_cast<unsigned>(offset + i)));
            emit("mov a," + dp(source + static_cast<unsigned>(i)));
            emit("mov [$02]+y,a");
        }
        return;
    }
    emit("mov a,$02");
    emit("clrc");
    emit("adc a,#" + hex8(static_cast<unsigned>(offset) & 0xFF));
    emit("mov " + dp(FarFrame) + ",a");
    emit("mov a,$03");
    emit("adc a,#" + hex8((static_cast<unsigned>(offset) >> 8) & 0xFF));
    emit("mov " + dp(FarFrame + 1) + ",a");
    for (int i = 0; i < bytes; ++i) {
        emit("mov y,#" + hex8(static_cast<unsigned>(i)));
        emit("mov a," + dp(source + static_cast<unsigned>(i)));
        emit("mov [" + dp(FarFrame) + "]+y,a");
    }
}

void SPC700CodeGenerator::loadWord(IRValueId value, unsigned destination, const Token& source) {
    const auto& type = typeOf(value, source);
    const auto bytes = slotBytes(type, source);
    if (bytes == 0) internal("void value used as an operand", source);
    frameRead(m_frame.value_offsets.at(value.value), destination, bytes);
    if (bytes == 2) return;
    emit("mov " + dp(destination + 1) + ",#$00");
    if (type.is_unsigned || type.base == BaseType::BOOL) return;
    const auto positive = newLabel();
    emit("mov a," + dp(destination));
    emit("bpl " + positive);
    emit("mov " + dp(destination + 1) + ",#$FF");
    bind(positive);
}

void SPC700CodeGenerator::storeValue(const IRInstruction& instruction, unsigned source) {
    const auto bytes = slotBytes(instruction.type, instruction.source);
    if (bytes == 0) return;
    frameWrite(m_frame.value_offsets.at(instruction.result.value), source, bytes);
}

void SPC700CodeGenerator::setWord(unsigned destination, std::uint16_t value) {
    emit("mov " + dp(destination) + ",#" + hex8(value & 0xFF));
    emit("mov " + dp(destination + 1) + ",#" + hex8(value >> 8));
}

void SPC700CodeGenerator::emitFault(std::uint8_t code) {
    // Fault channel: code on port 1, then the marker on port 0, then STOP.
    emit("mov " + dp(SPC700Target::Fault::CodePort) + ",#" + hex8(code));
    emit("mov " + dp(SPC700Target::Fault::MarkerPort) + ",#" + hex8(SPC700Target::Fault::Marker));
    emit("stop");
}

void SPC700CodeGenerator::negateWord(unsigned address) {
    emit("mov a,#$00");
    emit("setc");
    emit("sbc a," + dp(address));
    emit("mov " + dp(address) + ",a");
    emit("mov a,#$00");
    emit("sbc a," + dp(address + 1));
    emit("mov " + dp(address + 1) + ",a");
}

// ---- Blocks and instructions ------------------------------------------------

void SPC700CodeGenerator::emitBlock(const IRBasicBlock& block) {
    bind(blockLabel(block.id));
    for (const auto& instruction : block.instructions) emitInstruction(instruction);
}

void SPC700CodeGenerator::emitInstruction(const IRInstruction& instruction) {
    switch (instruction.opcode) {
        case IROpcode::Constant: {
            const auto value = instruction.operation == "null" ? 0 : static_cast<std::uint16_t>(instruction.immediate);
            setWord(T2, static_cast<std::uint16_t>(value));
            storeValue(instruction, T2);
            return;
        }
        case IROpcode::Address: emitAddress(instruction); return;
        case IROpcode::PointerOffset: emitPointerOffset(instruction); return;
        case IROpcode::PointerCompare: emitPointerCompare(instruction); return;
        case IROpcode::LoadIndirect: emitLoadIndirect(instruction); return;
        case IROpcode::StoreIndirect: emitStoreIndirect(instruction); return;
        case IROpcode::Binary: emitBinary(instruction); return;
        case IROpcode::Unary: emitUnary(instruction); return;
        case IROpcode::Cast: emitCast(instruction); return;
        case IROpcode::Call: emitCall(instruction); return;
        case IROpcode::Branch: emit("bra " + blockLabel(instruction.targets.at(0))); return;
        case IROpcode::CondBranch: emitCondBranch(instruction); return;
        case IROpcode::Switch: emitSwitch(instruction); return;
        case IROpcode::Return:
        case IROpcode::ReturnVoid: emitReturn(instruction); return;
        case IROpcode::Unreachable: emitFault(SPC700Target::Fault::InvalidAddress); return;
        case IROpcode::Phi: unsupported("SSA phi nodes (optimization levels above O0)", instruction.source);
        case IROpcode::MemoryInitialize: unsupported("local array initialization at O2", instruction.source);
        case IROpcode::DivMod:
        case IROpcode::DivModResult: unsupported("fused division pairs", instruction.source);
        case IROpcode::BitExtract: unsupported("bit extraction", instruction.source);
        case IROpcode::Load:
        case IROpcode::Store: internal("direct load/store opcodes are not produced by the lowerer", instruction.source);
        default: internal("GSU-only opcode reached the SPC700 backend", instruction.source);
    }
}

bool SPC700CodeGenerator::directSymbolAddress(IRValueId value, const Token& source) const {
    const auto& address = producer(value, source);
    return address.opcode == IROpcode::Address && (address.operation.empty() || address.operation == "temporary");
}

void SPC700CodeGenerator::emitAddress(const IRInstruction& instruction) {
    if (instruction.operation == "temporary" || (instruction.operation.empty() && instruction.symbol_id.isValid() &&
                                                 !m_data.hasSymbol(instruction.symbol))) {
        int offset = 0;
        int alignment = 1;
        if (instruction.operation == "temporary") {
            offset = localOffset(static_cast<int>(instruction.immediate));
        } else {
            const auto& table = locals();
            const auto found = table.find(instruction.symbol_id);
            if (found == table.end()) internal("local symbol is not in the current function", instruction.source);
            const auto stack = found->second.stackOffset;
            offset = stack < 0 ? localOffset(stack) : parameterOffset(stack);
            // A pointer slot keeps word alignment even when its pointee is an
            // over-aligned struct; only the object itself is padded.
            alignment = frameAlignment(found->second.type);
        }
        // T2 = FP + offset (offsets are below 32 KiB).
        emit("mov a,$02");
        emit("clrc");
        emit("adc a,#" + hex8(static_cast<unsigned>(offset) & 0xFF));
        emit("mov " + dp(T2) + ",a");
        emit("mov a,$03");
        emit("adc a,#" + hex8((static_cast<unsigned>(offset) >> 8) & 0xFF));
        emit("mov " + dp(T2 + 1) + ",a");
        if (alignment > 2) {
            // Round the allocation's base up, as the GSU backend does; the
            // analyzer reserved the padding.
            const auto mask = static_cast<unsigned>(alignment - 1);
            emit("mov a," + dp(T2));
            emit("clrc");
            emit("adc a,#" + hex8(mask));
            emit("and a,#" + hex8(~mask & 0xFF));
            emit("mov " + dp(T2) + ",a");
            emit("adc " + dp(T2 + 1) + ",#$00");
        }
        storeValue(instruction, T2);
        return;
    }
    if (instruction.operation == "member") {
        loadWord(instruction.operands.at(0), T2, instruction.source);
        if (instruction.immediate > 0) {
            if (instruction.immediate > 0xFFFF) unsupported("member offsets beyond 64 KiB", instruction.source);
            const auto ok = newLabel();
            emit("mov a," + dp(T2));
            emit("clrc");
            emit("adc a,#" + hex8(static_cast<unsigned>(instruction.immediate) & 0xFF));
            emit("mov " + dp(T2) + ",a");
            emit("mov a," + dp(T2 + 1));
            emit("adc a,#" + hex8((static_cast<unsigned>(instruction.immediate) >> 8) & 0xFF));
            emit("mov " + dp(T2 + 1) + ",a");
            emit("bcc " + ok);
            emitFault(SPC700Target::Fault::AddressOverflow);
            bind(ok);
        }
        storeValue(instruction, T2);
        return;
    }
    if (!instruction.operation.empty()) internal("unknown address operation '" + instruction.operation + "'", instruction.source);
    if (m_function->immutable_local_arrays.count(instruction.symbol_id))
        unsupported("immutable local array pools (O2)", instruction.source);
    if (!m_data.hasSymbol(instruction.symbol)) {
        if (m_function_symbols.count(instruction.symbol)) unsupported("function addresses", instruction.source);
        internal("unknown address symbol '" + instruction.symbol + "'", instruction.source);
    }
    const auto label = stripPrivate(m_data.getEntries().at(instruction.symbol).link_name);
    emit("mov " + dp(T2) + ",#<" + label);
    emit("mov " + dp(T2 + 1) + ",#>" + label);
    storeValue(instruction, T2);
}

void SPC700CodeGenerator::emitAddressCheck(const Type& pointer, int width, unsigned address) {
    const auto pointee = pointeeType(pointer);
    const auto alignment = width > 1 ? storageAlignment(pointee) : 1;
    if (alignment >= 2) {
        // Misalignment is tested before null, matching the GSU's order.
        const auto ok = newLabel();
        emit("mov a," + dp(address));
        emit("and a,#" + hex8(static_cast<unsigned>(alignment - 1) & 0xFF));
        emit("beq " + ok);
        emitFault(SPC700Target::Fault::Misaligned);
        bind(ok);
    }
    const auto nonnull = newLabel();
    emit("mov a," + dp(address));
    emit("or a," + dp(address + 1));
    emit("bne " + nonnull);
    emitFault(SPC700Target::Fault::InvalidAddress);
    bind(nonnull);
    if (width > 2) {
        // The whole access must stay inside the 16-bit address space.
        const auto limit = static_cast<unsigned>(65537 - width);
        const auto ok = newLabel();
        setWord(T3, static_cast<std::uint16_t>(limit));
        emit("movw ya," + dp(address));
        emit("cmpw ya," + dp(T3));
        emit("bcc " + ok);
        emitFault(SPC700Target::Fault::InvalidAddress);
        bind(ok);
    }
}

void SPC700CodeGenerator::emitPointerOffset(const IRInstruction& instruction) {
    if (instruction.operands.size() != 2 || (instruction.operation != "+" && instruction.operation != "-"))
        unsupported("scaled pointer recurrences (O2)", instruction.source);
    const auto& pointer = typeOf(instruction.operands[0], instruction.source);
    const auto& index_type = typeOf(instruction.operands[1], instruction.source);
    const auto stride = static_cast<unsigned>(instruction.immediate);
    if (stride == 0 || stride > 0xFFFF) internal("invalid pointer stride", instruction.source);
    loadWord(instruction.operands[0], T0, instruction.source);
    if (!directSymbolAddress(instruction.operands[0], instruction.source))
        emitAddressCheck(pointer, static_cast<int>(stride), T0);
    loadWord(instruction.operands[1], T1, instruction.source);
    // Direction: subtract for "-" or a negative signed index (not both).
    emit("mov " + dp(Signs) + ",#" + (instruction.operation == "-" ? std::string("$01") : std::string("$00")));
    if (!index_type.is_unsigned) {
        const auto positive = newLabel();
        emit("mov a," + dp(T1 + 1));
        emit("bpl " + positive);
        negateWord(T1);
        emit("mov a," + dp(Signs));
        emit("eor a,#$01");
        emit("mov " + dp(Signs) + ",a");
        bind(positive);
    }
    // T1 = |index| * stride; a magnitude beyond 16 bits leaves the address range.
    if (stride != 1) {
        setWord(T2, static_cast<std::uint16_t>(stride));
        // 16x16 multiply with overflow detection: the product of the high
        // bytes, and any carry into bit 16, fault.
        const auto ok = newLabel(), fault = newLabel();
        emit("mov a," + dp(T1 + 1));
        emit("beq " + ok);
        emit("mov a," + dp(T2 + 1));
        emit("bne " + fault);
        bind(ok);
        emit("mov a," + dp(T1));
        emit("mov y," + dp(T2));
        emit("mul ya");
        emit("movw " + dp(T3) + ",ya");
        emit("mov a," + dp(T1));
        emit("mov y," + dp(T2 + 1));
        emit("mul ya");
        emit("cmp y,#$00");
        emit("bne " + fault);
        emit("clrc");
        emit("adc a," + dp(T3 + 1));
        emit("bcs " + fault);
        emit("mov " + dp(T3 + 1) + ",a");
        emit("mov a," + dp(T1 + 1));
        emit("mov y," + dp(T2));
        emit("mul ya");
        emit("cmp y,#$00");
        emit("bne " + fault);
        emit("clrc");
        emit("adc a," + dp(T3 + 1));
        emit("bcs " + fault);
        emit("mov " + dp(T3 + 1) + ",a");
        emit("movw ya," + dp(T3));
        emit("movw " + dp(T1) + ",ya");
        const auto done = newLabel();
        emit("bra " + done);
        bind(fault);
        emitFault(SPC700Target::Fault::AddressOverflow);
        bind(done);
    }
    const auto subtract = newLabel(), checked = newLabel(), fault = newLabel();
    emit("mov a," + dp(Signs));
    emit("bne " + subtract);
    emit("movw ya," + dp(T0));
    emit("addw ya," + dp(T1));
    emit("bcs " + fault);
    emit("bra " + checked);
    bind(subtract);
    emit("movw ya," + dp(T0));
    emit("subw ya," + dp(T1));
    emit("bcs " + checked); // C set: no borrow.
    bind(fault);
    emitFault(SPC700Target::Fault::AddressOverflow);
    bind(checked);
    emit("movw " + dp(T2) + ",ya");
    emitAddressCheck(instruction.type, static_cast<int>(stride), T2);
    storeValue(instruction, T2);
}

void SPC700CodeGenerator::emitPointerCompare(const IRInstruction& instruction) {
    loadWord(instruction.operands.at(0), T0, instruction.source);
    loadWord(instruction.operands.at(1), T1, instruction.source);
    const auto equal = newLabel(), done = newLabel();
    emit("movw ya," + dp(T0));
    emit("cmpw ya," + dp(T1));
    emit("beq " + equal);
    setWord(T2, instruction.operation == "!=" ? 1 : 0);
    emit("bra " + done);
    bind(equal);
    setWord(T2, instruction.operation == "==" ? 1 : 0);
    bind(done);
    storeValue(instruction, T2);
}

void SPC700CodeGenerator::emitLoadIndirect(const IRInstruction& instruction) {
    const auto address = instruction.operands.at(0);
    const auto& pointer = typeOf(address, instruction.source);
    if (isFarPointer(pointer)) unsupported("far pointers (unavailable on SPC700)", instruction.source);
    const auto bytes = slotBytes(instruction.type, instruction.source);
    loadWord(address, Pointer, instruction.source);
    if (!directSymbolAddress(address, instruction.source)) emitAddressCheck(pointer, bytes, Pointer);
    // Byte, then high byte: a volatile word is read low first.
    for (int i = 0; i < bytes; ++i) {
        emit("mov y,#" + hex8(static_cast<unsigned>(i)));
        emit("mov a,[" + dp(Pointer) + "]+y");
        emit("mov " + dp(T2 + static_cast<unsigned>(i)) + ",a");
    }
    if (instruction.type.base == BaseType::BOOL && instruction.type.pointer_level == 0) normalizeBool(T2);
    if (instruction.type.pointer_level > 0) {
        // Null is a storable value, not an address; any other pointer read
        // from memory must be a valid address for its pointee.
        const auto done = newLabel();
        emit("mov a," + dp(T2));
        emit("or a," + dp(T2 + 1));
        emit("beq " + done);
        const auto element = pointeeType(instruction.type);
        emitAddressCheck(instruction.type, element.sizeInBytes > 0 ? element.sizeInBytes : 1, T2);
        bind(done);
    }
    storeValue(instruction, T2);
}

void SPC700CodeGenerator::emitStoreIndirect(const IRInstruction& instruction) {
    const auto address = instruction.operands.at(0);
    const auto& pointer = typeOf(address, instruction.source);
    if (isFarPointer(pointer)) unsupported("far pointers (unavailable on SPC700)", instruction.source);
    const auto bytes = slotBytes(instruction.type, instruction.source);
    loadWord(instruction.operands.at(1), T2, instruction.source);
    loadWord(address, Pointer, instruction.source);
    if (!directSymbolAddress(address, instruction.source)) emitAddressCheck(pointer, bytes, Pointer);
    for (int i = 0; i < bytes; ++i) {
        emit("mov y,#" + hex8(static_cast<unsigned>(i)));
        emit("mov a," + dp(T2 + static_cast<unsigned>(i)));
        emit("mov [" + dp(Pointer) + "]+y,a");
    }
}

void SPC700CodeGenerator::emitCall(const IRInstruction& instruction) {
    bool exported = false;
    const auto label = functionLabel(instruction.symbol, exported);
    // Arguments: one word slot each, pushed last to first so the first ends
    // lowest. Byte arguments occupy the low byte of their slot.
    for (auto argument = instruction.operands.rbegin(); argument != instruction.operands.rend(); ++argument) {
        loadWord(*argument, T0, instruction.source);
        emit("decw $00");
        emit("decw $00");
        emit("mov y,#$00");
        emit("mov a," + dp(T0));
        emit("mov [$00]+y,a");
        emit("inc y");
        emit("mov a," + dp(T0 + 1));
        emit("mov [$00]+y,a");
    }
    emit("call !" + label);
    const auto bytes = 2 * instruction.operands.size();
    if (bytes != 0) {
        emit("movw " + dp(T2) + ",ya");
        emit("mov a,$00");
        emit("clrc");
        emit("adc a,#" + hex8(bytes & 0xFF));
        emit("mov $00,a");
        emit("mov a,$01");
        emit("adc a,#" + hex8((bytes >> 8) & 0xFF));
        emit("mov $01,a");
    } else {
        emit("movw " + dp(T2) + ",ya");
    }
    if (instruction.result.isValid()) storeValue(instruction, T2);
}

void SPC700CodeGenerator::emitReturn(const IRInstruction& instruction) {
    if (instruction.opcode == IROpcode::Return && !instruction.operands.empty())
        loadWord(instruction.operands.front(), T2, instruction.source);
    emit("bra " + epilogueLabel());
}

void SPC700CodeGenerator::emitCondBranch(const IRInstruction& instruction) {
    const auto condition = instruction.operands.at(0);
    const auto bytes = slotBytes(typeOf(condition, instruction.source), instruction.source);
    frameRead(m_frame.value_offsets.at(condition.value), T0, bytes);
    emit("mov a," + dp(T0));
    if (bytes == 2) emit("or a," + dp(T0 + 1));
    emit("bne " + blockLabel(instruction.targets.at(0)));
    emit("bra " + blockLabel(instruction.targets.at(1)));
}

void SPC700CodeGenerator::emitSwitch(const IRInstruction& instruction) {
    loadWord(instruction.operands.at(0), T0, instruction.source);
    const auto cases = instruction.case_values.size();
    if (instruction.targets.size() < cases) internal("switch without enough targets", instruction.source);
    // Selector and case values compare as 16-bit patterns: the selector was
    // extended by its own type, so values outside its domain never match.
    for (std::size_t index = 0; index < cases; ++index) {
        const auto value = static_cast<std::uint16_t>(instruction.case_values[index]);
        const auto next = newLabel();
        emit("mov a," + dp(T0));
        emit("cmp a,#" + hex8(value & 0xFF));
        emit("bne " + next);
        emit("mov a," + dp(T0 + 1));
        emit("cmp a,#" + hex8(value >> 8));
        emit("beq " + blockLabel(instruction.targets[index]));
        bind(next);
    }
    if (instruction.targets.size() > cases) emit("bra " + blockLabel(instruction.targets.back()));
    else emitFault(SPC700Target::Fault::InvalidAddress);
}

// ---- Shared division helpers --------------------------------------------------

void SPC700CodeGenerator::emitDivisionHelpers() {
    if (!m_uses_unsigned_division && !m_uses_signed_division) return;
    // Unsigned 16-step restoring division: T0 / T1 -> T0 quotient, T3
    // remainder. A carry out of the remainder shift means the true remainder
    // exceeds 16 bits and is certainly at least the divisor.
    m_out << "\n__disco_spc_udiv:\n";
    emit("movw ya," + dp(T1));
    emit("bne __disco_spc_udiv_go");
    emitFault(SPC700Target::Fault::DivideByZero);
    bind("__disco_spc_udiv_go");
    setWord(T3, 0);
    emit("mov x,#16");
    bind("__disco_spc_udiv_loop");
    emit("asl " + dp(T0));
    emit("rol " + dp(T0 + 1));
    emit("rol " + dp(T3));
    emit("rol " + dp(T3 + 1));
    emit("bcs __disco_spc_udiv_sub");
    emit("movw ya," + dp(T3));
    emit("cmpw ya," + dp(T1));
    emit("bcc __disco_spc_udiv_next");
    bind("__disco_spc_udiv_sub");
    emit("movw ya," + dp(T3));
    emit("subw ya," + dp(T1));
    emit("movw " + dp(T3) + ",ya");
    emit("inc " + dp(T0));
    bind("__disco_spc_udiv_next");
    emit("dec x");
    emit("bne __disco_spc_udiv_loop");
    emit("ret");
    if (!m_uses_signed_division) return;
    // Signed: divide magnitudes, then the quotient takes the operands' sign
    // difference and the remainder the dividend's sign (truncation toward
    // zero; -32768 / -1 = -32768 with remainder 0 by modular negation).
    m_out << "\n__disco_spc_sdiv:\n";
    emit("movw ya," + dp(T1));
    emit("bne __disco_spc_sdiv_go");
    emitFault(SPC700Target::Fault::DivideByZero);
    bind("__disco_spc_sdiv_go");
    setWord(Signs, 0);
    emit("mov a," + dp(T0 + 1));
    emit("bpl __disco_spc_sdiv_p0");
    negateWord(T0);
    setWord(Signs, 0x0101);
    bind("__disco_spc_sdiv_p0");
    emit("mov a," + dp(T1 + 1));
    emit("bpl __disco_spc_sdiv_p1");
    negateWord(T1);
    emit("mov a," + dp(Signs));
    emit("eor a,#$01");
    emit("mov " + dp(Signs) + ",a");
    bind("__disco_spc_sdiv_p1");
    emit("call !__disco_spc_udiv");
    emit("mov a," + dp(Signs));
    emit("beq __disco_spc_sdiv_q");
    negateWord(T0);
    bind("__disco_spc_sdiv_q");
    emit("mov a," + dp(Signs + 1));
    emit("beq __disco_spc_sdiv_r");
    negateWord(T3);
    bind("__disco_spc_sdiv_r");
    emit("ret");
}
